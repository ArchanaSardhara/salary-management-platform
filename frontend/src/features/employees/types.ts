/** `ACTIVE` or soft-deleted (`DELETED`), as returned by the backend. */
export type EmployeeStatus = "ACTIVE" | "DELETED";

/** Statuses the directory can filter by. None selected means all statuses. */
export const EMPLOYEE_STATUS_FILTERS = ["active", "deleted"] as const;
export type EmployeeStatusFilter = (typeof EMPLOYEE_STATUS_FILTERS)[number];

export const EMPLOYEE_SORT_FIELDS = [
  "employeeNumber",
  "firstName",
  "email",
  "countryCode",
  "department",
  "jobTitle",
  "startDate",
] as const;
export type EmployeeSortField = (typeof EMPLOYEE_SORT_FIELDS)[number];
export type SortOrder = "asc" | "desc";

export interface Employee {
  id: string;
  /** Display code generated by the backend, e.g. "EMP-000042". */
  employeeCode: string;
  firstName: string;
  lastName: string | null;
  email: string | null;
  countryCode: string;
  department: string;
  jobTitle: string;
  /** Joining date, "YYYY-MM-DD". */
  startDate: string;
  endDate: string | null;
  status: EmployeeStatus;
  /** Optimistic-concurrency version; must be sent back on update. */
  version: number;
  createdAt: string;
  updatedAt: string;
  deletedAt: string | null;
}

export interface PageMeta {
  page: number;
  pageSize: number;
  total: number;
  totalPages: number;
}

export interface EmployeeListResponse {
  data: Employee[];
  meta: PageMeta;
}

export interface EmployeeOptions {
  countryCodes: string[];
  countriesInUse: string[];
  departments: string[];
  jobTitles: string[];
}

/** Directory filters, mirrored in the URL. Empty lists mean "no filter". */
export interface EmployeeListFilters {
  search: string;
  countryCodes: string[];
  departments: string[];
  statuses: EmployeeStatusFilter[];
  sortBy: EmployeeSortField;
  sortOrder: SortOrder;
}

// ---------------------------------------------------------------------------
// Compensation
// ---------------------------------------------------------------------------

export type PayFrequency = "MONTHLY" | "SEMI_MONTHLY" | "BI_WEEKLY" | "WEEKLY" | "ANNUAL";
export type CompensationType =
  | "BASE_SALARY"
  | "BONUS"
  | "COMMISSION"
  | "EQUITY_GRANT"
  | "ALLOWANCE";

export interface CompensationRecord {
  id: string;
  employeeId: string;
  amount: string;
  currencyCode: string;
  payFrequency: PayFrequency;
  type: CompensationType;
  effectiveFrom: string;
  effectiveTo: string | null;
  changeReason: string | null;
  createdAt: string;
  updatedAt: string;
}

export interface CompensationSnapshot {
  amount: string;
  currencyCode: string;
  payFrequency: PayFrequency;
  type: CompensationType;
  effectiveFrom: string;
  effectiveTo: string | null;
  changeReason: string | null;
}

export interface AuditLogEntry {
  id: string;
  compensationRecordId: string;
  changedById: string | null;
  changedAt: string;
  beforeValue: CompensationSnapshot | null;
  afterValue: CompensationSnapshot;
}

export interface PaginatedCompensation {
  data: CompensationRecord[];
  meta: { page: number; pageSize: number; total: number; totalPages: number };
}

export interface CurrencyOption {
  code: string;
  label: string;
}

export interface CreateCompensationPayload {
  amount: number;
  currencyCode: string;
  effectiveFrom: string;
  effectiveTo?: string;
  payFrequency?: PayFrequency;
  type?: CompensationType;
  changeReason?: string;
}

export interface UpdateCompensationPayload {
  effectiveTo: string | null;
}

// ---------------------------------------------------------------------------

export interface EmployeeFormPayload {
  firstName: string;
  lastName: string | null;
  email: string | null;
  countryCode: string;
  department: string;
  jobTitle: string;
  startDate: string;
  endDate: string | null;
}

export type CreateEmployeePayload = EmployeeFormPayload;

/** Only changed fields, plus the version the edit was based on. */
export type UpdateEmployeePayload = Partial<EmployeeFormPayload> & {
  version: number;
};
